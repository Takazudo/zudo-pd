"""Write the declarative B20 component projection that the inventory validator reads.

usage: python3 scripts/schgen/gen_b20_components.py [--check]

board_b20_spec.py builds COMPONENTS through helper functions, which the validator's restricted generator DSL does not
execute. This script imports the spec (after its reference annotation) and writes board_b20_components.py: the same
PROJECT_NAME and a literal COMPONENTS dictionary, one (symbol, value, lcsc, footprint, dnp, position) tuple per
reference. --check exits 1 when the committed projection differs from the spec. Never hand-edit the output.
"""
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / 'board_b20_components.py'


def render():
    sys.path.insert(0, str(HERE))
    spec = importlib.util.spec_from_file_location('board_b20_spec', HERE / 'board_b20_spec.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    lines = [
        '"""GENERATED by scripts/schgen/gen_b20_components.py from board_b20_spec.py; do not edit.',
        '',
        'Declarative projection of the B20 draft COMPONENTS for the central inventory provider (led-generator-v1).',
        '"""',
        '',
        f'PROJECT_NAME = {module.PROJECT_NAME!r}',
        '',
        'COMPONENTS = {',
    ]
    for ref in sorted(module.COMPONENTS, key=lambda r: (r.rstrip('0123456789'), int(r[len(r.rstrip('0123456789')):] or 0))):
        sym, value, lcsc, fp, dnp, (x, y) = module.COMPONENTS[ref]
        lines.append(f'    {ref!r}: ({sym!r}, {value!r}, {lcsc!r}, {fp!r}, {dnp!r}, ({round(x, 2)!r}, {round(y, 2)!r})),')
    lines += ['}', '']
    return '\n'.join(lines)


def main():
    text = render()
    if '--check' in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding='utf-8') != text:
            print(f'FAIL: {OUT.relative_to(HERE.parents[1])} differs from board_b20_spec.py; run gen_b20_components.py')
            return 1
        print('PASS: board_b20_components.py matches board_b20_spec.py')
        return 0
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT.relative_to(HERE.parents[1])}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
